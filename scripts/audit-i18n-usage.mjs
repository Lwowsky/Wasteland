/**
 * Conservative catalog usage inventory.
 * A translation is only marked "candidate" when its final key segment does
 * not occur anywhere in runtime source. Dynamic lookups, object spreads and
 * computed property access mean this is NOT proof that the key is unused.
 * No files are ever modified by this script.
 *
 * Usage: node scripts/audit-i18n-usage.mjs [--json]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIRS = ["src", "worker", "shared"];
const SOURCE_EXTENSIONS = new Set([".js", ".jsx", ".mjs"]);

// These names are generated by template strings in FlexibleShiftSettings.jsx;
// the literal keys "addShift1", etc., do not appear anywhere in source.
const KNOWN_DYNAMIC_FAMILIES = [
  /^admin\/distribution\.json:limits\.(?:add|applied|cap)Shift[1-4]$/,
];

function walk(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(absolute) : [absolute];
  });
}

export function flattenCatalog(value, prefix = "") {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return [{ key: prefix, value }];
  }
  return Object.entries(value).flatMap(([key, child]) =>
    flattenCatalog(child, prefix ? `${prefix}.${key}` : key));
}

export function inspectTranslationUsage(catalog, runtimeText, fileName) {
  const tokens = new Set(runtimeText.match(/[A-Za-z_$][\w$]*/g) || []);
  const candidates = [];
  const dynamic = [];
  for (const { key, value } of flattenCatalog(catalog)) {
    if (typeof value !== "string") continue;
    const name = key.slice(key.lastIndexOf(".") + 1);
    if (tokens.has(name)) continue; // Could be used: do not mark as dead.
    const fullName = `${fileName}:${key}`;
    if (KNOWN_DYNAMIC_FAMILIES.some((pattern) => pattern.test(fullName))) {
      dynamic.push(key);
    } else {
      candidates.push(key);
    }
  }
  return { candidates, dynamic };
}

export function createTranslationUsageReport(root = ROOT) {
  const runtimeFiles = SOURCE_DIRS.flatMap((dir) => walk(path.join(root, dir)))
    .filter((file) => SOURCE_EXTENSIONS.has(path.extname(file)))
    .filter((file) => !file.includes(`${path.sep}i18n${path.sep}locales${path.sep}`));
  const runtimeText = runtimeFiles.map((file) => fs.readFileSync(file, "utf8")).join("\n");
  const localeRoot = path.join(root, "src", "i18n", "locales", "uk");
  const catalogs = walk(localeRoot).filter((file) => file.endsWith(".json"));
  const entries = [];
  let totalKeys = 0;
  for (const file of catalogs) {
    const relative = path.relative(localeRoot, file).split(path.sep).join("/");
    const catalog = JSON.parse(fs.readFileSync(file, "utf8"));
    totalKeys += flattenCatalog(catalog).length;
    const usage = inspectTranslationUsage(catalog, runtimeText, relative);
    for (const key of usage.candidates) entries.push({ file: relative, key, category: "review" });
    for (const key of usage.dynamic) entries.push({ file: relative, key, category: "dynamic-protected" });
  }
  entries.sort((a, b) => (a.file + a.key).localeCompare(b.file + b.key));
  return { totalKeys, sourceFiles: runtimeFiles.length, entries };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = createTranslationUsageReport();
  if (process.argv.includes("--json")) {
    process.stdout.write(JSON.stringify(report, null, 2) + "\n");
  } else {
    const review = report.entries.filter((item) => item.category === "review");
    const dynamic = report.entries.filter((item) => item.category === "dynamic-protected");
    console.log(`I18N_USAGE_REVIEW: ${report.totalKeys} UA keys, ${report.sourceFiles} runtime files`);
    console.log(`${review.length} potential candidates for manual review; ${dynamic.length} computed keys protected.`);
    console.log("WARNING: this is a heuristic report, not proof of unused keys. Nothing was deleted.");
    review.forEach(({ file, key }) => console.log(`? ${file}:${key}`));
    dynamic.forEach(({ file, key }) => console.log(`* dynamic ${file}:${key}`));
  }
}
